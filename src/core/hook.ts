// Shell integration: a tiny prompt hook that remembers the last failed command (written
// by the shell itself, no Node process per prompt) and binds Alt+Z to `pikaclow fix`.
import { existsSync, mkdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import os from "node:os";
import { dirname, join, relative, isAbsolute } from "node:path";
import { appHome } from "./config.js";
import { capture, isWindows } from "./exec.js";
import type { ShellKind } from "./shell.js";

export type HookShell = "powershell" | "pwsh" | "bash" | "zsh" | "fish";

export const FIX_KEY = "Alt+Z";
const BEGIN = "# >>> pikaclow >>>";
const END = "# <<< pikaclow <<<";

/** Commands whose non-zero exit is an answer, not an error (grep found nothing…). */
export const QUIET_COMMANDS = ["pikaclow", "grep", "egrep", "fgrep", "rg", "ag", "diff", "cmp", "test", "[", "[[", "false", "which", "where", "type", "command", "exit", "man", "less", "more", "clear", "cls"];

export function hookShellFor(kind: ShellKind): HookShell | null {
  return kind === "cmd" || kind === "sh" ? null : kind;
}

export const lastFailedPath = () => join(appHome(), "last-failed");

const EXT: Record<HookShell, string> = { powershell: "ps1", pwsh: "ps1", bash: "bash", zsh: "zsh", fish: "fish" };
export const hookFilePath = (shell: HookShell) => join(appHome(), "hook." + EXT[shell]);

// ── Quoting ────────────────────────────────────────────────────────────────────
const psSingle = (s: string) => "'" + s.replace(/'/g, "''") + "'";
const shSingle = (s: string) => "'" + s.replace(/'/g, `'\\''`) + "'";
const fishSingle = (s: string) => "'" + s.replace(/\\/g, "\\\\").replace(/'/g, "\\'") + "'";

/**
 * A path as a shell expression. Paths under the home folder are written relative to
 * $HOME, which keeps profiles ASCII-only (Windows PowerShell 5.1 reads BOM-less files
 * in the ANSI code page) and lets Git Bash use its own /c/Users/… form.
 */
export function shellPath(shell: HookShell, abs: string, home = os.homedir()): string {
  const rel = relative(home, abs);
  const inside = rel && !rel.startsWith("..") && !isAbsolute(rel);
  if (shell === "powershell" || shell === "pwsh") {
    return inside ? `"$HOME\\${rel.replace(/\//g, "\\").replace(/[`$"]/g, "`$&")}"` : psSingle(abs);
  }
  const posix = rel.replace(/\\/g, "/");
  if (inside) return `"$HOME/${posix.replace(/[`$"\\]/g, "\\$&")}"`;
  return shell === "fish" ? fishSingle(abs.replace(/\\/g, "/")) : shSingle(abs.replace(/\\/g, "/"));
}

// ── Hook scripts ───────────────────────────────────────────────────────────────
/** The hook script for a shell. `hint` is the localized line shown after a failure. */
export function hookScript(shell: HookShell, hint: string): string {
  const state = shellPath(shell, lastFailedPath());
  const header = "# PikaClow shell integration. Generated by `pikaclow init`; run it again to update.";
  if (shell === "powershell" || shell === "pwsh") {
    const quiet = QUIET_COMMANDS.map(psSingle).join(", ");
    return `${header}
if (-not $global:__PikaClowHooked) {
  $global:__PikaClowHooked = $true
  $global:__PikaClowPrompt = $function:prompt
  $global:__PikaClowLastId = -1
  $global:__PikaClowSeenCode = $global:LASTEXITCODE
  $global:__PikaClowState = ${state}
  $global:__PikaClowQuiet = @(${quiet})
  # Base64 keeps this script ASCII-only, so it parses in any file encoding.
  $global:__PikaClowHint = [Text.Encoding]::UTF8.GetString([Convert]::FromBase64String('${Buffer.from(hint, "utf8").toString("base64")}'))
  function global:prompt {
    $ok = $global:?
    $code = $global:LASTEXITCODE
    try {
      $h = Get-History -Count 1
      if ($h -and $h.Id -ne $global:__PikaClowLastId) {
        $global:__PikaClowLastId = $h.Id
        # $LASTEXITCODE only belongs to this command if it changed; cmdlet errors report 1.
        $exit = if ($code -is [int] -and $code -ne 0 -and $code -ne $global:__PikaClowSeenCode) { $code } else { 1 }
        $first = (($h.CommandLine.Trim() -split '\\s+')[0] -replace '^.*[\\\\/]', '' -replace '\\.(exe|cmd|bat|ps1)$', '').ToLower()
        if (-not $ok -and $exit -ne 130 -and $exit -ne -1073741510 -and $global:__PikaClowQuiet -notcontains $first) {
          $edition = if ($PSVersionTable.PSEdition -eq 'Core') { 'pwsh' } else { 'powershell' }
          [IO.File]::WriteAllLines($global:__PikaClowState, [string[]]@([string]$exit, $edition, (Get-Location).ProviderPath, $h.CommandLine))
          if ($env:PIKACLOW_HINT -ne '0') { Write-Host ("  $([char]0x26A1) exit $exit $([char]0xB7) " + $global:__PikaClowHint) -ForegroundColor DarkYellow }
        }
      }
    } catch {}
    $global:__PikaClowSeenCode = $code
    $global:LASTEXITCODE = $code
    if ($global:__PikaClowPrompt) { & $global:__PikaClowPrompt } else { "PS $($executionContext.SessionState.Path.CurrentLocation)$('>' * ($nestedPromptLevel + 1)) " }
  }
  if (Get-Command Set-PSReadLineKeyHandler -ErrorAction SilentlyContinue) {
    Set-PSReadLineKeyHandler -Chord 'Alt+z' -BriefDescription 'PikaClowFix' -Description 'Explain the last failed command (pikaclow fix)' -ScriptBlock {
      [Microsoft.PowerShell.PSConsoleReadLine]::RevertLine()
      [Microsoft.PowerShell.PSConsoleReadLine]::Insert('pikaclow fix')
      [Microsoft.PowerShell.PSConsoleReadLine]::AcceptLine()
    }
  }
}
`;
  }
  const quietCase = QUIET_COMMANDS.map((q) => q.replace(/[[\]]/g, "\\$&")).join("|");
  const hintSh = shSingle(hint);
  if (shell === "bash") {
    return `${header}
if [[ $- == *i* && -z \${__pikaclow_hooked-} ]]; then
  __pikaclow_hooked=1
  __pikaclow_last=''
  __pikaclow_hook() {
    local code=$? entry cmd first
    entry=$(HISTTIMEFORMAT= builtin history 1)
    if [[ $entry != "$__pikaclow_last" ]]; then
      __pikaclow_last=$entry
      if (( code != 0 && code != 130 )) && [[ $entry =~ ^[[:space:]]*[0-9]+[*]?[[:space:]]+(.*)$ ]]; then
        cmd=\${BASH_REMATCH[1]}
        first=\${cmd%% *}
        first=\${first##*/}
        case $first in
          ${quietCase}) ;;
          *)
            printf '%s\\n%s\\n%s\\n%s\\n' "$code" bash "$PWD" "$cmd" > ${state} 2>/dev/null
            [[ \${PIKACLOW_HINT-} == 0 ]] || printf '\\033[33m  ⚡ exit %s · %s\\033[0m\\n' "$code" ${hintSh} >&2
            ;;
        esac
      fi
    fi
    return $code
  }
  PROMPT_COMMAND="__pikaclow_hook\${PROMPT_COMMAND:+;$PROMPT_COMMAND}"
  bind '"\\ez": "\\C-a\\C-kpikaclow fix\\C-m"' 2>/dev/null
fi
`;
  }
  if (shell === "zsh") {
    return `${header}
if [[ -o interactive && -z \${__pikaclow_hooked-} ]]; then
  typeset -g __pikaclow_hooked=1 __pikaclow_cmd=''
  __pikaclow_preexec() { __pikaclow_cmd=$1 }
  __pikaclow_precmd() {
    local code=$? cmd=$__pikaclow_cmd first
    __pikaclow_cmd=''
    [[ -z $cmd ]] && return $code
    (( code == 0 || code == 130 )) && return $code
    first=\${\${(z)cmd}[1]}
    first=\${first:t}
    case $first in
      ${quietCase}) return $code ;;
    esac
    print -r -- "$code"$'\\n'zsh$'\\n'"$PWD"$'\\n'"$cmd" >| ${state} 2>/dev/null
    [[ \${PIKACLOW_HINT-} == 0 ]] || printf '\\033[33m  ⚡ exit %s · %s\\033[0m\\n' "$code" ${hintSh} >&2
    return $code
  }
  autoload -Uz add-zsh-hook
  add-zsh-hook preexec __pikaclow_preexec
  precmd_functions=(__pikaclow_precmd $precmd_functions)
  __pikaclow_fix_widget() { BUFFER='pikaclow fix'; zle accept-line }
  zle -N __pikaclow_fix_widget
  bindkey '^[z' __pikaclow_fix_widget
fi
`;
  }
  // fish
  const quietFish = QUIET_COMMANDS.map(fishSingle).join(" ");
  return `${header}
if status is-interactive; and not set -q __pikaclow_hooked
  set -g __pikaclow_hooked 1
  function __pikaclow_postexec --on-event fish_postexec
    set -l code $status
    if test $code -eq 0 -o $code -eq 130; or test -z "$argv[1]"
      return
    end
    set -l first (string split -m1 ' ' -- (string trim -- $argv[1]))[1]
    set first (string replace -r '.*/' '' -- $first)
    if contains -- $first ${quietFish}
      return
    end
    printf '%s\\n%s\\n%s\\n%s\\n' $code fish $PWD $argv[1] > ${state} 2>/dev/null
    if test "$PIKACLOW_HINT" != 0
      printf '\\e[33m  ⚡ exit %s · %s\\e[0m\\n' $code ${fishSingle(hint)} >&2
    end
  end
  bind \\ez 'commandline -r "pikaclow fix"; commandline -f execute'
end
`;
}

// ── Profiles ───────────────────────────────────────────────────────────────────
/** The startup file the shell reads, where the one-line loader goes. */
export async function profilePath(shell: HookShell): Promise<string> {
  const home = os.homedir();
  if (shell === "powershell" || shell === "pwsh") {
    const exe = shell === "pwsh" ? "pwsh" : isWindows ? "powershell.exe" : "pwsh";
    const out = await capture(exe, ["-NoLogo", "-NoProfile", "-Command", "[Console]::Out.Write($PROFILE.CurrentUserCurrentHost)"], { timeout: 15000 });
    if (out?.trim()) return out.trim();
    const docs = join(home, "Documents");
    return shell === "pwsh" || !isWindows
      ? join(isWindows ? docs : join(home, ".config"), isWindows ? "PowerShell" : "powershell", "Microsoft.PowerShell_profile.ps1")
      : join(docs, "WindowsPowerShell", "Microsoft.PowerShell_profile.ps1");
  }
  if (shell === "zsh") return join(process.env.ZDOTDIR || home, ".zshrc");
  if (shell === "fish") return join(process.env.XDG_CONFIG_HOME || join(home, ".config"), "fish", "config.fish");
  return join(home, ".bashrc");
}

/** The marker block added to the profile: it only sources the hook file if it exists. */
export function loaderBlock(shell: HookShell, hookFile = hookFilePath(shell), eol = "\n"): string {
  const p = shellPath(shell, hookFile);
  const line =
    shell === "powershell" || shell === "pwsh"
      ? `if (Test-Path -LiteralPath ${p}) { . ${p} }`
      : shell === "fish"
        ? `test -f ${p}; and source ${p}`
        : `[ -f ${p} ] && . ${p}`;
  return [BEGIN, line, END].join(eol);
}

const BLOCK_RE = /(\r?\n)?# >>> pikaclow >>>[\s\S]*?# <<< pikaclow <<<(\r?\n)?/;

export function hasLoader(profileText: string): boolean {
  return BLOCK_RE.test(profileText);
}

/** Adds (or refreshes) the loader block, keeping the file's line endings. */
export function withLoader(profileText: string, block: string): string {
  const eol = profileText.includes("\r\n") ? "\r\n" : "\n";
  const b = block.replace(/\r?\n/g, eol);
  if (hasLoader(profileText)) return profileText.replace(BLOCK_RE, (_m, lead: string | undefined) => (lead ? eol : "") + b + eol);
  const sep = profileText === "" ? "" : profileText.endsWith(eol) ? eol : eol + eol;
  return profileText + sep + b + eol;
}

export function withoutLoader(profileText: string): string {
  const eol = profileText.includes("\r\n") ? "\r\n" : "\n";
  // Also swallow the blank line withLoader put before the block.
  return profileText.replace(/(\r?\n)*# >>> pikaclow >>>[\s\S]*?# <<< pikaclow <<<(\r?\n)?/, eol).replace(new RegExp(`^${eol}`), "");
}

function readText(path: string): string {
  try {
    return readFileSync(path, "utf8").replace(/^\uFEFF/, "");
  } catch {
    return "";
  }
}

export interface InstallResult {
  profile: string;
  hookFile: string;
  updated: boolean;
}

/** Writes the hook file and makes sure the profile loads it. Idempotent. */
export async function installHook(shell: HookShell, hint: string): Promise<InstallResult> {
  const hookFile = hookFilePath(shell);
  mkdirSync(dirname(hookFile), { recursive: true });
  const script = hookScript(shell, hint);
  const ps = shell === "powershell" || shell === "pwsh";
  // PowerShell 5.1 needs a BOM to read the hook (⚡, Vietnamese hint) as UTF-8.
  writeFileSync(hookFile, ps ? "\uFEFF" + script.replace(/\n/g, "\r\n") : script);
  const profile = await profilePath(shell);
  const before = existsSync(profile) ? readFileSync(profile, "utf8") : "";
  const bom = before.startsWith("\uFEFF") ? "\uFEFF" : "";
  const text = before.replace(/^\uFEFF/, "");
  const updated = hasLoader(text);
  mkdirSync(dirname(profile), { recursive: true });
  writeFileSync(profile, bom + withLoader(text, loaderBlock(shell, hookFile, ps && isWindows ? "\r\n" : "\n")));
  return { profile, hookFile, updated };
}

export async function uninstallHook(shell: HookShell): Promise<{ profile: string; removed: boolean }> {
  const profile = await profilePath(shell);
  const raw = existsSync(profile) ? readFileSync(profile, "utf8") : "";
  const bom = raw.startsWith("\uFEFF") ? "\uFEFF" : "";
  const text = raw.replace(/^\uFEFF/, "");
  const removed = hasLoader(text);
  if (removed) writeFileSync(profile, bom + withoutLoader(text));
  rmSync(hookFilePath(shell), { force: true });
  return { profile, removed };
}

export async function isHookInstalled(shell: HookShell): Promise<boolean> {
  if (!existsSync(hookFilePath(shell))) return false;
  return hasLoader(readText(await profilePath(shell)));
}

// ── Last failed command ────────────────────────────────────────────────────────
export interface FailedCommand {
  code: number;
  shell: string;
  cwd: string;
  command: string;
  at: number;
}

/** Git Bash and MSYS write /c/Users/…; Node on Windows needs C:\Users\…. */
export function nativePath(p: string): string {
  if (!isWindows) return p;
  const m = /^\/([a-zA-Z])(\/.*)?$/.exec(p);
  return m ? `${m[1]!.toUpperCase()}:${(m[2] ?? "/").replace(/\//g, "\\")}` : p;
}

export function parseFailed(text: string, at = 0): FailedCommand | null {
  const lines = text.replace(/^\uFEFF/, "").replace(/\r\n/g, "\n").replace(/\n+$/, "").split("\n");
  if (lines.length < 4) return null;
  const code = Number(lines[0]);
  const command = lines.slice(3).join("\n").trim();
  if (!Number.isFinite(code) || !command) return null;
  return { code, shell: lines[1]!.trim(), cwd: nativePath(lines[2]!.trim()), command, at };
}

export function readLastFailed(): FailedCommand | null {
  const file = lastFailedPath();
  try {
    return parseFailed(readFileSync(file, "utf8"), statSync(file).mtimeMs);
  } catch {
    return null;
  }
}

/** Used by the interactive mode for its own `!command` runs. */
export function writeLastFailed(f: Omit<FailedCommand, "at">): void {
  try {
    mkdirSync(appHome(), { recursive: true });
    writeFileSync(lastFailedPath(), [String(f.code), f.shell, f.cwd, f.command].join("\n") + "\n");
  } catch {
    // best-effort
  }
}

export function clearLastFailed(): void {
  rmSync(lastFailedPath(), { force: true });
}
